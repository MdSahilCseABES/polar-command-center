/**
 * THE THIN LAYER OVER SUPABASE
 * ============================
 * Three functions — read a table, insert a row, update a row — and one rule:
 *
 *   NOTHING IN THIS FILE EVER THROWS.
 *
 * Every function returns a plain object you can look at. That is what lets
 * DataContext call the database without wrapping each call in try/catch, and
 * it is why a dead network cannot take the console down (master prompt
 * section 15: the UI must never crash on an API failure).
 *
 * WHY THIS FILE EXISTS AT ALL, when the five service files sit next to it:
 *   Those five files say WHAT each module stores — its table name, its
 *   columns, its sort order. This one says HOW any table is talked to. Split
 *   that way, "we now send a timeout with every query" is a change to one
 *   function here instead of the same edit made five times, five chances to
 *   get it wrong.
 *
 * THE ONE SUPABASE BEHAVIOUR THAT SURPRISES EVERYONE:
 *   If a table exists but has no Row Level Security policy allowing reads,
 *   a SELECT does not fail. It succeeds and returns ZERO ROWS. So "empty" and
 *   "not allowed" look identical from here. That is the single most common
 *   way a Supabase setup goes wrong, so readTable() reports the difference
 *   between "no rows" and "an error", and DataContext explains it in words.
 */

import { supabase } from '../lib/supabase'

/* Stop waiting after this long. A hanging request leaves the app on its
   loading skeleton forever, which looks exactly like a crash. Ten seconds is
   generous for a free-tier database on venue wifi. */
const TIMEOUT_MS = 10000

/**
 * Turn whatever Supabase (or the network) gave us into one readable sentence.
 *
 * The raw errors are accurate but not friendly: a missing table arrives as
 * 'relation "public.cargo" does not exist', which means nothing until you
 * know it means "you did not run the SQL yet".
 */
export function describeDbError(error) {
  if (!error) return null

  const code = error.code || ''
  const message = error.message || String(error)

  if (message.includes('aborted') || error.name === 'AbortError') {
    return 'The database did not answer in time. It may be waking up from sleep — try again in a moment.'
  }
  if (message.includes('Failed to fetch') || message.includes('NetworkError')) {
    return 'Could not reach the database. Check your internet connection and that the project URL is right.'
  }
  /* 42P01 = undefined_table. Nearly always "the SQL has not been run". */
  if (code === '42P01' || message.includes('does not exist')) {
    return 'The tables are not there yet. Open supabase/schema.sql and run it in the Supabase SQL Editor.'
  }
  /* 42501 = insufficient_privilege, which for the anon key means RLS said no. */
  if (code === '42501' || message.toLowerCase().includes('row-level security')) {
    return 'The database refused the write. The Row Level Security policies at the bottom of supabase/schema.sql have not been created.'
  }
  /* 23505 = unique_violation. Our IDs are generated by counting existing
     rows, so this is what a duplicate ID looks like. */
  if (code === '23505') {
    return 'A row with that ID already exists in the database.'
  }
  /* 23514 = check_violation: the status word is not one the schema allows. */
  if (code === '23514') {
    return 'The database rejected that value — it is not one of the status words the schema allows.'
  }
  if (code === '401' || code === 'PGRST301' || message.includes('JWT')) {
    return 'The database rejected the key. Check VITE_SUPABASE_ANON_KEY in your .env file.'
  }
  return message
}

/** An AbortSignal that fires after TIMEOUT_MS. */
function timeoutSignal() {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS)
  return { signal: controller.signal, done: () => clearTimeout(timer) }
}

/**
 * ONE READ IS NOT ONE REQUEST — WORTH KNOWING BEFORE YOU OPEN DEVTOOLS.
 *
 * The Supabase library retries a failed read by itself: up to three more
 * attempts with a growing pause between them, for reads only (never writes,
 * which must not be repeated). So one unreachable database produces FOUR red
 * lines in the browser console per table, and the five tables together
 * produce twenty. It looks alarming and it is nothing — it is one failure
 * being tried again, politely.
 *
 * WE LEAVE THAT ON DELIBERATELY. The failure this prototype is most likely to
 * meet is a hall full of people on one wifi network, where a request fails
 * once and works a second later. Retrying is exactly right for that, and the
 * alternative — falling back to demo data on the first hiccup — would be
 * worse. If you ever want a single attempt instead, add .retry(false) to the
 * query below.
 *
 * In development you will see twice as many again. React's StrictMode mounts
 * every component twice on purpose, to catch code that misbehaves when it
 * runs more than once. It does not happen in a production build.
 */

/**
 * READ ONE WHOLE TABLE.
 *
 * Returns { rows, error }:
 *   rows   an array, ALWAYS — empty rather than null, so callers can map
 *          over it without checking
 *   error  a readable sentence, or null
 *
 * `orderBy` keeps the order stable between refreshes. Without it Postgres is
 * free to return rows in any order it likes, and a table that reshuffles
 * itself every reload looks broken even though nothing is wrong.
 */
export async function readTable(table, orderBy = 'id') {
  if (!supabase) return { rows: [], error: null, skipped: true }

  const { signal, done } = timeoutSignal()
  try {
    const { data, error } = await supabase
      .from(table)
      .select('*')
      .order(orderBy, { ascending: true })
      .abortSignal(signal)

    if (error) return { rows: [], error: describeDbError(error) }
    return { rows: Array.isArray(data) ? data : [], error: null }
  } catch (err) {
    /* supabase-js normally hands errors back in `error`, but a genuinely
       broken URL or an abort can still throw. Both end up here. */
    return { rows: [], error: describeDbError(err) }
  } finally {
    done()
  }
}

/**
 * INSERT ONE ROW.
 *
 * Returns { error } — a sentence or null. We do not return the inserted row,
 * because the app has already added it to the screen (see the write-through
 * comment in DataContext). This call exists to make it durable, not to find
 * out what it says.
 */
export async function insertRow(table, record) {
  if (!supabase) return { error: null, skipped: true }

  const { signal, done } = timeoutSignal()
  try {
    const { error } = await supabase.from(table).insert(record).abortSignal(signal)
    return { error: error ? describeDbError(error) : null }
  } catch (err) {
    return { error: describeDbError(err) }
  } finally {
    done()
  }
}

/**
 * UPDATE ONE ROW BY ID.
 *
 * `changes` is the same small patch object the UI already passes around —
 * { status: 'DELAYED' } — so only the touched columns are sent. Sending the
 * whole record would overwrite a column somebody else changed a second ago.
 */
export async function updateRow(table, id, changes) {
  if (!supabase) return { error: null, skipped: true }

  const { signal, done } = timeoutSignal()
  try {
    const { error } = await supabase.from(table).update(changes).eq('id', id).abortSignal(signal)
    return { error: error ? describeDbError(error) : null }
  } catch (err) {
    return { error: describeDbError(err) }
  } finally {
    done()
  }
}

/**
 * DELETE ONE ROW BY ID.
 *
 * Here for completeness of the CRUD set, and used by deleteExpedition. It is
 * the only destructive call in the project, which is why it is the only one
 * that names the table and the id together in its comment: there is no undo.
 */
export async function deleteRow(table, id) {
  if (!supabase) return { error: null, skipped: true }

  const { signal, done } = timeoutSignal()
  try {
    const { error } = await supabase.from(table).delete().eq('id', id).abortSignal(signal)
    return { error: error ? describeDbError(error) : null }
  } catch (err) {
    return { error: describeDbError(err) }
  } finally {
    done()
  }
}
